"""Extra credit: decrypt supplied educational RSA/DH traffic using public data."""
import argparse
import glob
import json
import logging
import sys
from pathlib import Path
from crypto_math import (decrypt_message, dh_aes_key, dh_parameter_error, is_prime,
                         mod_inverse, mod_pow, rsa_decrypt_key, validate_rsa_public)


def read_transcript(path):
    text = Path(path).read_text(encoding='utf-8-sig')
    decoder, messages = json.JSONDecoder(), []
    while text.strip():
        text = text.lstrip()
        message, end = decoder.raw_decode(text)
        if not isinstance(message, dict):
            raise ValueError('a transcript must contain JSON objects')
        messages.append(message)
        text = text[end:]
    return messages


def factor_modulus(n):
    for p in range(400, 501):
        if n % p == 0:
            q = n // p
            if 400 <= q <= 500 and p != q and is_prime(p) and is_prime(q):
                return p, q
    raise ValueError('no distinct prime factors in the assignment range')


def discrete_log(g, public, p):
    """At most p-1 modular multiplications, since p is at most 500."""
    value = 1
    for exponent in range(p - 1):
        if value == public:
            return exponent
        value = value * g % p
    raise ValueError('DH public value is not generated by g')


def break_transcript(messages, initiator='Alice'):
    if initiator not in ('Alice', 'Bob'):
        raise ValueError('initiator must be Alice or Bob')
    responder = 'Bob' if initiator == 'Alice' else 'Alice'
    if not messages or messages[0].get('opcode') != 0:
        raise ValueError('transcript must start with the protocol request')
    protocol = messages[0].get('type')
    if protocol not in ('RSA', 'DH'):
        raise ValueError('Eve expects a Protocol II (RSA) or III (DH) transcript')
    if len(messages) not in (4, 5):
        raise ValueError('expected one session with a handshake and 1 or 2 AES messages')
    offer, reply = messages[1:3]
    if offer.get('opcode') != 1 or offer.get('type') != protocol:
        raise ValueError('missing public-key offer')
    params = offer.get('parameter', {})
    if protocol == 'RSA':
        n, e = params.get('n'), offer.get('public')
        validate_rsa_public(e, n)
        if reply.get('opcode') != 2 or reply.get('type') != 'RSA':
            raise ValueError('missing RSA-encrypted AES key')
        p, q = factor_modulus(n)
        phi = (p - 1) * (q - 1)
        d = mod_inverse(e, phi)
        key = rsa_decrypt_key(reply.get('encrypted_key'), d, n)
        recovered = {'p': p, 'q': q, 'n': n, 'e': e, 'phi': phi, 'd': d}
    else:
        p, g = params.get('p'), params.get('g')
        error = dh_parameter_error(p, g)
        if error:
            raise ValueError(error)
        if reply.get('opcode') != 1 or reply.get('type') != 'DH':
            raise ValueError('missing Alice DH public key')
        bob_public, alice_public = offer.get('public'), reply.get('public')
        if any(type(value) is not int or not 1 <= value < p
               for value in (bob_public, alice_public)):
            raise ValueError('invalid DH public value')
        bob_private = discrete_log(g, bob_public, p)
        shared = mod_pow(alice_public, bob_private, p)
        key = dh_aes_key(shared)
        recovered = {'p': p, 'g': g, f'{responder.lower()}_public': bob_public,
                     f'{initiator.lower()}_public': alice_public,
                     f'{responder.lower()}_private_mod_p_minus_1': bob_private, 'shared_secret': shared}
    plaintexts = []
    for index, message in enumerate(messages[3:]):
        if message.get('opcode') != 2 or message.get('type') != 'AES':
            raise ValueError('expected an AES message after key exchange')
        plaintexts.append({'direction': f'{responder} -> {initiator}' if index == 0 else f'{initiator} -> {responder}',
                           'text': decrypt_message(key, message.get('encryption'))})
    return {'protocol': protocol, 'recovered': recovered,
            'aes_key_hex': key.hex(), 'plaintexts': plaintexts}


def run_offline(files, output=None, initiator='Alice'):
    paths = []
    for pattern in files:
        matches = sorted(glob.glob(pattern))
        paths.extend(matches or [pattern])
    results, failed = [], False
    for path in dict.fromkeys(paths):
        try:
            result = break_transcript(read_transcript(path), initiator)
            result['file'] = Path(path).name
            results.append(result)
            print(f"\n[{result['file']}] {result['protocol']}")
            print('Recovered:', json.dumps(result['recovered'], ensure_ascii=False))
            print('AES key (hex):', result['aes_key_hex'])
            for item in result['plaintexts']:
                print(f"{item['direction']}: {item['text']}")
        except (OSError, ValueError, TypeError, KeyError) as exc:
            failed = True
            results.append({'file': str(path), 'error': str(exc)})
            print(f'ERROR [{path}]: {exc}')
    if output:
        output = Path(output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(results, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return 1 if failed else 0


def main():
    parser = argparse.ArgumentParser(description='Extra credit: offline logs or a live RSA/DH relay')
    sub = parser.add_subparsers(dest='mode', required=True)
    offline = sub.add_parser('offline', help='Decrypt saved public JSON traffic')
    offline.add_argument('files', nargs='+', help='Files or quoted glob patterns')
    offline.add_argument('--output', help='Optional JSON results file')
    offline.add_argument('--initiator', choices=['Alice', 'Bob'], default='Alice',
                         help='Who sent opcode 0; use Bob for the optional reversed-role mode')
    relay = sub.add_parser('relay', help='Forward bytes unchanged and decrypt a copy')
    relay.add_argument('-A', '--listen-addr', default='0.0.0.0')
    relay.add_argument('-P', '--listen-port', type=int, required=True)
    relay.add_argument('-a', '--addr', required=True, help="Bob's actual IP address")
    relay.add_argument('-p', '--port', type=int, required=True, help="Bob's actual port")
    relay.add_argument('--timeout', type=float, default=30.0)
    relay.add_argument('--once', action='store_true')
    relay.add_argument('--transcript', help='Save public JSON; server adds session numbers')
    relay.add_argument('-l', '--log', default='WARNING',
                       choices=['DEBUG', 'INFO', 'WARNING', 'ERROR', 'CRITICAL'])
    argv = sys.argv[1:]
    # Keep the previous "python eve.py logfile" interface usable.
    if argv and argv[0] not in ('offline', 'relay', '-h', '--help'):
        argv = ['offline', *argv]
    args = parser.parse_args(argv)
    if args.mode == 'offline':
        return run_offline(args.files, args.output, args.initiator)
    from relay import run_relay
    logging.basicConfig(level=args.log, format='%(levelname)s: %(message)s')
    try:
        return run_relay(args.listen_addr, args.listen_port, args.addr, args.port,
                         args.timeout, args.once, args.transcript)
    except (OSError, ValueError) as exc:
        logging.error('Eve: %s', exc)
        return 1
    except KeyboardInterrupt:
        return 0


if __name__ == '__main__':
    raise SystemExit(main())
